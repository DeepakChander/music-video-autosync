"""Helper smoke test (no Premiere needed). Talks to a running helper over 127.0.0.1.

  python tools/helper_smoke.py                       # self-test media generated by the helper
  python tools/helper_smoke.py --master song.wav --clips D:/footage

Checks: /health (FFmpeg found), token auth rejects a wrong token, master analysis, probe,
a full analysis job (progress until done), result completeness, FCP7 XML export, and for the
self-test media the accuracy gate against known truth. Exit code 0 only if every check passed.
"""

from __future__ import annotations

import argparse
import json
import os
import ssl
import subprocess
import sys
import time
import urllib.error
import urllib.request

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from helper.config import DEFAULT_PORT, TOKEN_HEADER, HelperConfig, token_path  # noqa: E402

SSL_CONTEXT = None


def https_context(cafile):
    """Verify the helper's certificate. mkcert's root lives in `mkcert -CAROOT`; Python does not
    read the macOS keychain, so it is passed explicitly."""
    if not cafile:
        try:
            root = subprocess.run(["mkcert", "-CAROOT"], capture_output=True, text=True, check=True).stdout.strip()
            cafile = os.path.join(root, "rootCA.pem")
        except (OSError, subprocess.CalledProcessError):
            cafile = None
    return ssl.create_default_context(cafile=cafile) if cafile else ssl.create_default_context()


def call(url: str, token: str, method: str = "GET", body=None, timeout: float = 600):
    data = json.dumps(body).encode() if body is not None else None
    req = urllib.request.Request(url, data=data, method=method,
                                 headers={TOKEN_HEADER: token, "Content-Type": "application/json"})
    try:
        with urllib.request.urlopen(req, timeout=timeout, context=SSL_CONTEXT) as r:
            return r.status, json.loads(r.read() or b"{}")
    except urllib.error.HTTPError as e:
        return e.code, json.loads(e.read() or b"{}")


def main(argv=None) -> int:
    p = argparse.ArgumentParser()
    p.add_argument("--port", type=int, default=DEFAULT_PORT)
    p.add_argument("--token-file", default=token_path())
    p.add_argument("--master")
    p.add_argument("--clips", nargs="*", default=[])
    p.add_argument("--count", type=int, default=24, help="self-test takes to generate")
    p.add_argument("--fps", default="24000/1001")
    p.add_argument("--wait", type=float, default=30.0, help="seconds to wait for the helper to come up")
    p.add_argument("--https", action="store_true", help="talk https (default: whatever the helper config says)")
    p.add_argument("--cafile", help="CA file to verify the helper's certificate (default: mkcert's root)")
    a = p.parse_args(argv)
    global SSL_CONTEXT
    scheme = "https" if (a.https or HelperConfig.load().scheme == "https") else "http"
    if scheme == "https":
        SSL_CONTEXT = https_context(a.cafile)
    base = f"{scheme}://127.0.0.1:{a.port}"
    results: list[tuple[str, bool, str]] = []

    def check(name, ok, detail=""):
        results.append((name, bool(ok), detail))
        print(f"[{'PASS' if ok else 'FAIL'}] {name} {detail}", flush=True)
        return ok

    try:
        token = open(a.token_file, encoding="utf-8").read().strip()
    except OSError as e:
        check("token file readable", False, str(e))
        return 1
    # A helper started a moment ago may still be loading (first start compiles its Python files).
    deadline = time.time() + a.wait
    while True:
        try:
            st, h = call(base + "/health", token, timeout=5)
            break
        except (urllib.error.URLError, OSError) as e:
            if time.time() >= deadline:
                check("helper reachable", False, f"{base}: {e} (is the helper running?)")
                return 1
            time.sleep(1)
    check("health", st == 200 and h.get("ffmpeg_found"), f"version={h.get('version')} ffmpeg={h.get('ffmpeg')}")
    st, _ = call(base + "/health", "wrong-token", timeout=5)
    check("wrong token rejected", st == 401, f"status={st}")
    num, den = (a.fps.split("/") + ["1"])[:2]
    seq = {"fps_num": int(num), "fps_den": int(den), "width": 1920, "height": 1080}

    t0 = time.time()
    if a.master:
        st, m = call(base + "/master", token, "POST", {"path": a.master})
        check("master analysed", st == 200, f"duration={m.get('duration_s')}s" if st == 200 else str(m))
        folders = [c for c in a.clips if os.path.isdir(c)]
        files = [c for c in a.clips if os.path.isfile(c)]
        st, pr = call(base + "/probe", token, "POST", {"paths": files, "folders": folders})
        clip_paths = [f["path"] for f in pr.get("files", [])]
        check("probe", st == 200 and clip_paths, f"{len(clip_paths)} files, {pr.get('total_duration_s')} s")
        st, j = call(base + "/jobs", token, "POST", {"master_path": a.master, "clip_paths": clip_paths, "sequence": seq})
    else:
        st, j = call(base + "/selftest", token, "POST", {"count": a.count, "sequence": seq})
    if not check("job created", st == 201, str(j)):
        return 1
    job_id = j["job_id"]
    last = None
    while True:
        st, js = call(f"{base}/jobs/{job_id}", token, timeout=10)
        pg = js.get("progress", {})
        line = f"{js.get('state')} {pg.get('phase')} {pg.get('done')}/{pg.get('total')}"
        if line != last:
            print("   ", line, flush=True)
            last = line
        if js.get("state") in ("done", "failed", "cancelled", "interrupted"):
            break
        time.sleep(1)
    elapsed = time.time() - t0
    check("job finished", js["state"] == "done", f"state={js['state']} in {elapsed:.1f}s error={js.get('error')}")
    st, res = call(f"{base}/jobs/{job_id}/result", token)
    n = len(res.get("clips", []))
    check("every clip reported", st == 200 and n == pg.get("total"), f"{n} clips, summary={res.get('summary')}")
    st, x = call(f"{base}/jobs/{job_id}/export/fcp7xml", token, "POST", {})
    check("FCP7 XML exported", st == 200 and os.path.isfile(x.get("path", "")), x.get("path", str(x)))
    if not a.master:
        st, acc = call(f"{base}/jobs/{job_id}/accuracy", token)
        m = acc.get("metrics", {})
        check("self-test accuracy gate", st == 200 and not acc.get("gate_failures"),
              f"within 1 frame {m.get('position_within_1_frame_pct')}%, wrong HIGH/MEDIUM {m.get('wrong_HIGH_or_MEDIUM')}, "
              f"failures {acc.get('gate_failures')}")
    # First cut: shot analysis (OpenCV + YuNet must load, also in the frozen build) and a cut.
    st, sh = call(f"{base}/jobs/{job_id}/shots", token, "POST", {"faces": True})
    while st == 200 and sh.get("state") == "running":
        time.sleep(1)
        st, sh = call(f"{base}/jobs/{job_id}/shots", token)
    takes = sh.get("takes", []) if st == 200 else []
    readable = [t for t in takes if not t.get("error")]
    check("shot analysis (face detector loaded)", st == 200 and sh.get("state") == "done" and readable
          and all(t.get("face_detector") == "yunet" for t in readable),
          f"{len(readable)}/{len(takes)} clips analysed, detector {sorted({t.get('face_detector') for t in readable})}"
          if st == 200 else str(sh))
    st, cut = call(f"{base}/jobs/{job_id}/cut", token, "POST", {"style": "performance", "colour": True})
    check("first cut with colour match", st == 200 and os.path.isfile(cut.get("xml_path", "")) and cut.get("colour"),
          f"{cut.get('stats', {}).get('shots')} shots, hero {cut.get('colour', {}).get('hero_name')}" if st == 200 else str(cut))
    failed = [r for r in results if not r[1]]
    print(f"\n{len(results) - len(failed)}/{len(results)} checks passed; job {job_id}")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
